CREATE TABLE IF NOT EXISTS public.funcionario (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome_funcionario VARCHAR(255), cargo_funcionario VARCHAR(255),
 email_funcionairo VARCHAR(255) UNIQUE NOT NULL
);
CREATE TABLE IF NOT EXISTS public.tarefa (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 titulo VARCHAR(255), descricao VARCHAR(255), data_criacao DATE,
 status VARCHAR(255) CHECK (status IN ('Pendente','Em_Andamento','Comcluida')),
 funcionario_id BIGINT REFERENCES public.funcionario(id)
);
